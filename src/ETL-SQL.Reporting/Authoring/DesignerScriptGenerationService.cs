    private static void AppendLine(StringBuilder builder, string value, string lineEnding) =>
        builder.Append(value).Append(lineEnding);

    private static void TrimTrailingComma(StringBuilder builder, string lineEnding)
    {
        var suffix = "," + lineEnding;
        if (builder.Length >= suffix.Length
            && builder.ToString(builder.Length - suffix.Length, suffix.Length) == suffix)
            builder.Remove(builder.Length - suffix.Length, 1);
    }
