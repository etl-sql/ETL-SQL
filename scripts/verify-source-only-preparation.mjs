#!/usr/bin/env node
/**
 * Proves the checkout can regenerate every browser output from its retained inputs.
 *
 * Deletes each inventoried output and both preparation manifests, prepares again, and requires the
 * same paths with the same bytes. While outputs are tracked, a plain `sync-assets.js` on a fresh
 * checkout finds everything already in place and proves nothing about a tree without them.
 *
 * Every output is checked against its recorded hash before anything is removed, and the original
 * bytes are put back if preparation fails, so a failed run leaves the checkout as it found it.
 *
 * Usage:
 *   node scripts/verify-source-only-preparation.mjs [--evidence <file>]
 */
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { readOwnership, browserInputSignature, safeAssetPath } = require('./lib/browser-asset-inputs.cjs');
const { syncAssets } = require('./sync-assets.js');

const defaultRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifests = ['artifacts/browser-assets.json', 'artifacts/browser-assets.props'];
const sha256 = content => createHash('sha256').update(content).digest('hex');

export async function verifySourceOnlyPreparation({ root = defaultRoot, toolchain = defaultRoot, prepare = syncAssets } = {}) {
    root = path.resolve(root);
    if (!fs.existsSync(path.join(root, manifests[0])))
        throw new Error('Browser ownership inventory is missing. Run node scripts/sync-assets.js first.');
    const before = readOwnership(root);
    if (before.version !== 2) throw new Error('Browser ownership inventory has no output hashes. Run node scripts/sync-assets.js first.');
    const saved = new Map();
    for (const owner of before.outputs) {
        const file = safeAssetPath(root, owner.path);
        const content = fs.existsSync(file) ? fs.readFileSync(file) : null;
        if (!content || sha256(content) !== owner.sha256)
            throw new Error(`Prepared output is missing or differs from the inventory: ${owner.path}. Run node scripts/sync-assets.js first.`);
        saved.set(owner.path, content);
    }
    for (const relative of manifests) {
        const file = safeAssetPath(root, relative);
        if (fs.existsSync(file)) saved.set(relative, fs.readFileSync(file));
    }
    const inputs = browserInputSignature(root);

    for (const relative of saved.keys()) fs.unlinkSync(path.join(root, relative));
    try {
        // With no inventory, the signature treats nothing as generated; it must still equal the
        // signature taken with every output present, or an output was feeding preparation.
        if (browserInputSignature(root) !== inputs)
            throw new Error('Removing generated outputs changed the retained input signature.');
        await prepare({ root, toolchain, quiet: true });
        await prepare({ root, toolchain, quiet: true, check: true });
        const after = readOwnership(root);
        const expected = new Map(before.outputs.map(owner => [owner.path, owner]));
        const problems = [];
        for (const owner of after.outputs) {
            const prior = expected.get(owner.path);
            if (!prior) problems.push(`Unexpected output after source-only preparation: ${owner.path}`);
            else if (prior.sha256 !== owner.sha256 || prior.source !== owner.source || prior.kind !== owner.kind)
                problems.push(`Output differs after source-only preparation: ${owner.path}`);
            else if (sha256(fs.readFileSync(path.join(root, owner.path))) !== owner.sha256)
                problems.push(`Regenerated bytes do not match the inventory: ${owner.path}`);
            expected.delete(owner.path);
        }
        for (const missing of expected.keys()) problems.push(`Output was not regenerated: ${missing}`);
        if (problems.length) throw new Error(problems.join('\n'));
        return { outputs: after.outputs, inputSignature: inputs };
    } catch (error) {
        for (const [relative, content] of saved) {
            fs.mkdirSync(path.dirname(path.join(root, relative)), { recursive: true });
            fs.writeFileSync(path.join(root, relative), content);
        }
        throw error;
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const evidenceAt = process.argv.indexOf('--evidence');
    try {
        const result = await verifySourceOnlyPreparation();
        if (evidenceAt > 0) {
            const file = path.resolve(process.argv[evidenceAt + 1]);
            fs.mkdirSync(path.dirname(file), { recursive: true });
            fs.writeFileSync(file, JSON.stringify({ node: process.version, platform: process.platform,
                retainedInputSignature: result.inputSignature, outputs: result.outputs }, null, 2) + '\n');
        }
        console.log(`source-only preparation: ${result.outputs.length} outputs regenerated with identical bytes.`);
    } catch (error) {
        console.error(error.message);
        process.exit(1);
    }
}
