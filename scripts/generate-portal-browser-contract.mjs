import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptRoot = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptRoot, '..');
export function generatePortalBrowserContract(root = repoRoot) {
    const source = path.join(root, 'src', 'ETL-SQL.Portal', 'BrowserContracts', 'critical-api-contracts.json');
    const contracts = JSON.parse(fs.readFileSync(source, 'utf8'));
    if (!contracts || typeof contracts !== 'object' || Array.isArray(contracts) || !Object.keys(contracts).length)
        throw new Error('Portal API contract schema must contain named contracts.');
    const supported = new Set(['string', 'number', 'boolean', 'object']);
    for (const [name, contract] of Object.entries(contracts)) {
        if (!contract || !['array', 'object'].includes(contract.kind)) throw new Error(`Invalid API contract kind: ${name}`);
        if (contract.kind === 'array') {
            if (typeof contract.items !== 'string' || !Object.hasOwn(contracts, contract.items))
                throw new Error(`Unknown API array item contract: ${name}`);
        } else {
            if (!contract.fields || typeof contract.fields !== 'object' || Array.isArray(contract.fields))
                throw new Error(`Invalid API contract fields: ${name}`);
            for (const type of Object.values(contract.fields)) {
                if (typeof type !== 'string' || !(supported.has(type.replace(/\[\]$/, '')) ||
                    Object.hasOwn(contracts, type.replace(/\[\]$/, ''))))
                    throw new Error(`Unknown API contract field type: ${name}`);
            }
        }
    }

    return `/* GENERATED by scripts/generate-portal-browser-contract.mjs. Do not edit directly. */
const contracts = ${JSON.stringify(contracts, null, 2)};

function fail(contractName, path, expected, value) {
    const actual = value === null ? 'null' : Array.isArray(value) ? 'array' : typeof value;
    throw new TypeError(\`API contract \${contractName} failed at \${path}: expected \${expected}, received \${actual}.\`);
}

function validateType(contractName, path, expected, value) {
    if (expected.endsWith('[]')) {
        if (!Array.isArray(value)) fail(contractName, path, expected, value);
        const itemType = expected.slice(0, -2);
        value.forEach((item, index) => validateType(contractName, \`\${path}[\${index}]\`, itemType, item));
        return;
    }
    if (contracts[expected]) {
        validateContract(expected, value, path, contractName);
        return;
    }
    if (expected === 'object') {
        if (!value || typeof value !== 'object' || Array.isArray(value)) fail(contractName, path, expected, value);
        return;
    }
    if (typeof value !== expected) fail(contractName, path, expected, value);
}

function validateContract(name, value, path = '$', rootName = name) {
    const contract = contracts[name];
    if (!contract) throw new TypeError(\`Unknown API contract: \${name}.\`);
    if (contract.kind === 'array') {
        if (!Array.isArray(value)) fail(rootName, path, 'array', value);
        value.forEach((item, index) => validateContract(contract.items, item, \`\${path}[\${index}]\`, rootName));
        return;
    }
    if (!value || typeof value !== 'object' || Array.isArray(value)) fail(rootName, path, 'object', value);
    for (const [field, type] of Object.entries(contract.fields)) {
        if (!(field in value)) fail(rootName, \`\${path}.\${field}\`, type, undefined);
        validateType(rootName, \`\${path}.\${field}\`, type, value[field]);
    }
}

export function assertApiContract(name, value) {
    validateContract(name, value);
    return value;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const output = path.join(repoRoot, 'src', 'ETL-SQL.Portal', 'wwwroot', 'js', 'api-contracts.generated.js');
    const check = process.argv.includes('--check');
    const generated = generatePortalBrowserContract();
    if (check) {
        if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
            console.error('Portal browser API contract is stale. Run: node scripts/generate-portal-browser-contract.mjs');
            process.exit(1);
        }
        console.log('Portal browser API contract is current.');
    } else {
        const { bootstrapBrowserContracts } = await import('./generate-browser-contracts.mjs');
        const result = await bootstrapBrowserContracts();
        console.log(`Generated ${result.outputs.length} browser contracts. Run node scripts/sync-assets.js, then its -Check mode.`);
    }
}
