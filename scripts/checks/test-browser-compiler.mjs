import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { compileBrowser } from '../compile-browser.mjs';
import assetInputs from '../lib/browser-asset-inputs.cjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'etlsql-browser-compiler-'));
const source = path.join(root, 'src/ETL-SQL.ReportRuntime/Resources/TypeScript');
const output = path.join(root, 'src/ETL-SQL.ReportRuntime/Resources/Shared');
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };
const compile = check => compileBrowser({ root, toolchain: repo, check });
try {
    fs.copyFileSync(path.join(repo, 'tsconfig.browser-build.json'), path.join(root, 'tsconfig.browser-build.json'));
    write(path.join(source, 'leaf.ts'), 'export const amount: number = 7;\n');
    write(path.join(output, 'legacy.js'), "import { amount } from './leaf.js';\nexport function twice() { return amount * 2; }\n");
    write(path.join(source, 'entry.ts'), "import { twice } from './legacy.js';\nexport const result: number = twice();\n");
    write(path.join(source, 'nested/consumer.ts'), "import { amount } from '../leaf.js';\nexport const nested: number = amount;\n");
    assert.throws(() => compile(true), /missing or stale/);
    compile(false);
    const leaf = path.join(output, 'leaf.js');
    const expected = fs.readFileSync(leaf, 'utf8');
    const legacy = fs.readFileSync(path.join(output, 'legacy.js'), 'utf8');
    assert.throws(() => compileBrowser({ root, toolchain: root }), /Browser toolchain:.*npm ci/);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected, 'Standalone compilation must validate its restored toolchain before writing.');
    compile(true);
    const earlierFormat = expected.replace('*/\n// @ts-nocheck — generated implementation; check the TypeScript owner.\n', '*/\n');
    const bootstrapInventory = path.join(root, 'artifacts/browser-assets.json');
    fs.unlinkSync(bootstrapInventory);
    write(leaf, earlierFormat);
    assert.throws(() => compile(true), /missing or stale/, 'Verification cannot upgrade an earlier generated format.');
    compile(false);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected, 'Bootstrap must reproduce the complete earlier emit before upgrading its format.');
    fs.unlinkSync(bootstrapInventory);
    write(leaf, earlierFormat + '\n// a local edit beyond the reproducible format\n');
    assert.throws(() => compile(false), /retained or locally edited/);
    write(leaf, expected);
    compile(false);
    assert.match(fs.readFileSync(path.join(output, 'nested/consumer.js'), 'utf8'), /from '\.\.\/leaf\.js'/);
    compile(false);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected);
    assert.equal(fs.readFileSync(path.join(output, 'legacy.js'), 'utf8'), legacy);
    // Generated output must not shadow the source when checking migrated imports.
    write(leaf, expected + '\ninvalid generated syntax !!!');
    assert.throws(() => compile(true), /retained or locally edited/);
    assert.throws(() => compile(false), /retained or locally edited/);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected + '\ninvalid generated syntax !!!', 'Preparation must preserve local output changes.');
    fs.unlinkSync(leaf); // Explicitly discard this test's deliberate corruption before regeneration.
    compile(false);
    // An invalid source must not write even other valid changed modules.
    write(path.join(source, 'leaf.ts'), 'export const amount: number = 8;\n');
    write(path.join(source, 'entry.ts'), "import { amount } from './leaf.js';\nexport const result: string = amount;\n");
    assert.throws(() => compile(false), /not assignable/);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected);
    write(path.join(source, 'entry.ts'), 'export enum Unsupported { One }\n');
    assert.throws(() => compile(false), /erasableSyntaxOnly/);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected);
    fs.rmSync(path.join(source, 'leaf.ts'));
    assert.throws(() => compile(true), /Orphaned/);
    assert.throws(() => compile(false), /erasableSyntaxOnly/);
    assert.equal(fs.readFileSync(leaf, 'utf8'), expected, 'Failed compilation cannot remove orphaned output.');
    fs.rmSync(path.join(source, 'entry.ts'));
    fs.rmSync(path.join(source, 'nested/consumer.ts'));
    compile(false);
    assert.equal(fs.existsSync(leaf), false);
    assert.equal(fs.readFileSync(path.join(output, 'legacy.js'), 'utf8'), legacy, 'Cleanup must preserve authored JavaScript.');
    write(path.join(source, 'fresh.ts'), 'export const fresh: number = 9;\n');
    compile(false);
    fs.renameSync(path.join(source, 'fresh.ts'), path.join(source, 'renamed.ts'));
    assert.throws(() => compile(true), /Orphaned/);
    compile(false);
    assert.equal(fs.existsSync(path.join(output, 'fresh.js')), false);
    assert.match(fs.readFileSync(path.join(output, 'renamed.js'), 'utf8'), /fresh = 9/);
    compile(true);
    console.log('browser compiler: mixed imports, drift, idempotence, rename/delete cleanup and failed-compile checks passed');

    const renamed = path.join(output, 'renamed.js');
    const beforeClaim = fs.readFileSync(renamed);
    const claim = path.join(source, 'claimed.ts');
    const retained = path.join(output, 'claimed.js');
    write(claim, 'export const claimed = true;\n');
    write(retained, '/* GENERATED TYPESCRIPT OUTPUT - DO NOT EDIT. */\nexport const authored = true;\n');
    write(path.join(source, 'renamed.ts'), 'export const fresh: number = 10;\n');
    assert.throws(() => compile(false), /retained or locally edited/, 'A generated-looking banner cannot authorize replacing an authored module.');
    assert.deepEqual(fs.readFileSync(renamed), beforeClaim, 'A conflicting output must stop all compiler writes.');
    assert.match(fs.readFileSync(retained, 'utf8'), /authored = true/);
    fs.unlinkSync(claim);
    const forged = path.join(output, 'forged.js');
    write(forged, '/* GENERATED TYPESCRIPT OUTPUT - DO NOT EDIT. */\nexport const retained = 1;\n');
    const signature = assetInputs.browserInputSignature(root);
    fs.appendFileSync(forged, '// authored edit\n');
    assert.notEqual(assetInputs.browserInputSignature(root), signature, 'Authored modules with generated-looking banners remain input fingerprints.');
    compile(false);
    assert.equal(fs.existsSync(forged), true, 'A forged output banner cannot authorize deletion.');
    assert.equal(fs.existsSync(retained), true);
    const inventoryFile = path.join(root, 'artifacts/browser-assets.json');
    const goodInventory = fs.readFileSync(inventoryFile, 'utf8');
    const duplicate = JSON.parse(goodInventory);
    duplicate.outputs.push({ ...duplicate.outputs[0], path: duplicate.outputs[0].path.replace('renamed.js', 'Renamed.js'),
        source: duplicate.outputs[0].source.replace('renamed.ts', 'Renamed.ts') });
    write(inventoryFile, JSON.stringify(duplicate));
    assert.throws(() => compile(false), /Duplicate browser output owner/, 'Case-only ownership collisions must fail on every platform.');
    write(inventoryFile, goodInventory);
    for (const invalidPath of ['../outside.js', 'src/../outside.js', 'C:/outside.js', 'src\\outside.js']) {
        const inventory = JSON.parse(goodInventory);
        inventory.outputs[0].path = invalidPath;
        write(inventoryFile, JSON.stringify(inventory));
        assert.throws(() => compile(false), /ownership path|output owner/);
        assert.equal(fs.existsSync(forged), true);
    }
    write(inventoryFile, '{ invalid json');
    assert.throws(() => compile(false), /Malformed browser ownership/);
    write(inventoryFile, goodInventory);
    const ownerSource = path.join(source, 'renamed.ts');
    const ownerContent = fs.readFileSync(ownerSource);
    const generatedContent = fs.readFileSync(renamed);
    fs.unlinkSync(ownerSource);
    fs.appendFileSync(renamed, '// local output edit\n');
    assert.throws(() => compile(false), /contains local edits/);
    assert.equal(fs.existsSync(renamed), true);
    write(renamed, generatedContent);
    compile(false);
    assert.equal(fs.existsSync(renamed), false, 'Only an unchanged, inventoried obsolete file may be removed.');
    write(ownerSource, ownerContent);
    compile(false);
    const staleImport = path.join(source, 'stale-import.ts');
    write(staleImport, "import { fresh } from './renamed.js';\nexport const result: number = fresh;\n");
    fs.unlinkSync(ownerSource);
    assert.throws(() => compile(false), /Cannot find module/, 'A deleted source must not resolve through its obsolete generated implementation.');
    assert.equal(fs.existsSync(renamed), true, 'Missing dependencies must stop cleanup and retain the last delivery set.');
    fs.unlinkSync(staleImport);
    write(ownerSource, ownerContent);
    const external = path.join(root, 'outside-output');
    fs.mkdirSync(external);
    const junction = path.join(output, 'escaped');
    fs.symlinkSync(external, junction, process.platform === 'win32' ? 'junction' : 'dir');
    write(path.join(source, 'escaped/probe.ts'), 'export const escaped = true;\n');
    assert.throws(() => compile(false), /symlink or junction/);
    assert.equal(fs.existsSync(path.join(external, 'probe.js')), false);
    fs.unlinkSync(junction);
    fs.unlinkSync(path.join(source, 'escaped/probe.ts'));
    console.log('browser ownership: retained banners, local edits, traversal, malformed inventories and junction escapes are rejected before writes');
    const portal = path.join(root, 'src/ETL-SQL.Portal/BrowserSources');
    write(path.join(portal, 'page.ts'), "import { fresh } from './Renamed.js';\nexport const result: number = fresh;\n");
    assert.throws(() => compile(false), /casing does not match/, 'Import casing must remain portable to Linux.');
    write(path.join(portal, 'page.ts'), "import { fresh } from './renamed.js';\nexport const result: number = fresh;\n");
    compile(false);
    const pageOutput = path.join(root, 'src/ETL-SQL.Portal/wwwroot/js/page.js');
    assert.match(fs.readFileSync(pageOutput, 'utf8'), /from '\.\/renamed\.js'/);
    write(path.join(portal, 'page.ts'), "import { fresh } from './renamed.js';\nexport const result: string = fresh;\n");
    assert.throws(() => compile(false), /not assignable/, 'Portal imports must use shared TypeScript contracts even with no host copies.');
    write(path.join(portal, 'page.ts'), "import { fresh } from './renamed.js';\nexport const result: number = fresh;\n");
    fs.mkdirSync(path.join(root, 'types'));
    // Exercise declaration/generic resolution independently of Portal DTO-generator changes.
    write(path.join(root, 'types/contracts.d.ts'), `
        interface FolderDto { id: number; name: string; }
        interface PagedResult<T> { items: T[]; total: number; page: number; pageSize: number; }
        interface LoginResponse { expiresAt: string; }
    `);
    const probe = path.join(portal, 'contract-probe.ts');
    write(probe, "export const page: PagedResult<FolderDto> = { items: [], total: 0, page: 1, pageSize: 25 };\nexport const expires: LoginResponse['expiresAt'] = '2026-01-01T00:00:00Z';\n");
    compile(false);
    write(probe, "export const page: PagedResult<FolderDto> = { items: ['wrong item'], total: 0, page: 1, pageSize: 25 };\n");
    assert.throws(() => compile(false), /not assignable/, 'Ambient generic declarations must constrain page item types.');
    write(probe, "export const page: PagedResult<FolderDto> = { items: [], total: 0, page: 1, pageSize: 25 };\n");
    write(path.join(source, 'designer/bridge.ts'), "import { amount } from './vendor.js';\nexport interface Context { count: ReturnType<typeof amount>; }\nexport const context: Context = { count: amount() };\n");
    write(path.join(output, 'designer/vendor.js'), 'export function amount() { return 4; }\n');
    write(path.join(portal, 'page.ts'), "import type { Context } from '../designer/bridge.js';\nexport const context: Context = { count: 4 };\n");
    compile(false);
    assert.match(fs.readFileSync(pageOutput, 'utf8'), /count: 4/);
    assert.doesNotMatch(fs.readFileSync(pageOutput, 'utf8'), /bridge\.js/);
    write(path.join(portal, 'page.ts'), "import type { Context } from '../designer/bridge.js';\nexport const context: Context = { count: 'wrong' };\n");
    assert.throws(() => compile(false), /not assignable/, 'Portal type imports must retain shared vendor dependency types.');
    console.log('browser compiler: shared-to-Portal imports resolve to typed owners before host generation');
} finally { fs.rmSync(root, { recursive: true, force: true }); }

const utilPath = path.join(repo, 'src/ETL-SQL.ReportRuntime/Resources/Shared/rt-util.js');
const util = await import(`data:text/javascript;base64,${Buffer.from(fs.readFileSync(utilPath, 'utf8')).toString('base64')}`);
assert.equal(util.safeUrl(' javascript:alert(1) '), '#');
// The browser drops tab/LF/CR anywhere and C0 controls at the ends before parsing the scheme.
assert.equal(util.safeUrl('java\tscript:alert(1)'), '#');
assert.equal(util.safeUrl('java\nscript:alert(1)'), '#');
assert.equal(util.safeUrl('\u0001javascript:alert(1)'), '#');
assert.equal(util.safeUrl('https://example.com/a?b=1'), 'https://example.com/a?b=1');
assert.equal(util.safeUrl('/reports/one'), '/reports/one');
assert.equal(util.escHtml('<>&"\''), '&lt;&gt;&amp;&quot;&#39;');
assert.equal(util.escHtml(null), '');
assert.equal(util.interpolateUrlTemplate({ url: '/?q={Name}&x={Other}', urlParams: ['name'] }, ['a&b'], ['NAME']), '/?q=a%26b&x=');
assert.deepEqual(util.parseMultiParameter('["a",2]'), ['a', '2']);
assert.deepEqual(util.parseMultiParameter(' a, ,b '), ['a', 'b']);
assert.equal(util.getOption({ TiTlE: 'hello' }, 'TITLE'), 'hello');
assert.equal(util.formatValue(12.5, 'N1'), '12.5');
assert.equal(util.formatValue('12.5', 'N1'), '12.5');
assert.equal(util.formatValue('bad', 'N1'), 'bad');
assert.equal(util.toCssLength(12), '12px');
assert.equal(util.interpolateColor('#000', '#fff', 0.5), 'rgb(128,128,128)');
assert.match(util.simpleMarkdown('# Heading\n\n```sql\n<x>\n```'), /&lt;x&gt;/);
assert.equal(util.renderInlineMarkdown('<img> **safe**'), '&lt;img&gt; <strong>safe</strong>');
console.log('runtime utility pilot: coercion, URL, escaping, formatting and markdown checks passed');

const designerPath = path.join(repo, 'src/ETL-SQL.ReportRuntime/Resources/Shared/designer/designer-util.js');
const designer = await import(`data:text/javascript;base64,${Buffer.from(fs.readFileSync(designerPath, 'utf8')).toString('base64')}`);
assert.equal(designer.escapeHtml('<>&"\''), '&lt;&gt;&amp;&quot;\'');
assert.equal(designer.esc('<>&"\''), '&lt;&gt;&amp;&quot;\'');
for (const escape of [designer.escapeHtml, designer.esc]) {
    assert.equal(escape(null), '');
    assert.equal(escape(undefined), '');
    assert.equal(escape(0), '0');
    assert.equal(escape(false), 'false');
}
console.log('designer utility: existing escaping and coercion behavior preserved');

const toolbar = await import(pathToFileURL(path.join(repo, 'src/ETL-SQL.ReportRuntime/Resources/Shared/designer/editor-toolbar.js')).href);
const button = toolbar.toolbarButton({ attr: 'data-save', icon: 'save', title: 'Save "draft"', label: '<Save>', primary: true, key: 'Ctrl+S' });
